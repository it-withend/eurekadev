/**
 * Reproducible accuracy report: npm run validate
 *
 * Runs every built-in experiment many times on every simulated phone platform,
 * with randomised (but seeded, so deterministic) setups, and writes
 * docs/VALIDATION.md. Clone the repo, run this, get the same numbers.
 *
 * Reported per experiment × platform:
 *  - success rate (analysis returned a result),
 *  - mean and worst error against the simulated ground truth,
 *  - uncertainty honesty: how often the truth lies within ±2σ of the result
 *    (an honest ±2σ should contain it ~95 % of the time).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { registry } from '../src/experiments/index';
import { speedOfSound } from '../src/experiments/resonance/analyze';
import { AUDIO_RATES, captureAudio, captureOnPlatform, MOTION_PLATFORMS } from '../src/testing/platforms';
import { rng, synthCentripetal, synthPendulum, synthResonance } from '../src/testing/synthetic';
import type { Recording } from '../src/core/types';
import { stress } from './stress';

const RUNS = 20;

interface Row {
  experiment: string;
  platform: string;
  ok: number;
  errors: number[];
  within2: number;
}

function run(experiment: string, platform: string, make: (i: number) => { rec: Recording; truth: number }): Row {
  const def = registry.get(experiment)!;
  const row: Row = { experiment: def.title, platform, ok: 0, errors: [], within2: 0 };
  for (let i = 0; i < RUNS; i++) {
    let rec: Recording;
    let truth: number;
    try {
      ({ rec, truth } = make(i));
    } catch {
      continue; // the platform rejected the capture (counted as a failure)
    }
    const r = def.analyze(rec);
    if (!r.ok) continue;
    row.ok++;
    const err = Math.abs(r.primary.measured - truth) / Math.abs(truth);
    row.errors.push(err);
    // Compare with the measurement's own uncertainty (reference uncertainty excluded: truth is exact here).
    if (Math.abs(r.primary.measured - truth) <= 2 * r.primary.uncertainty) row.within2++;
  }
  return row;
}

const rows: Row[] = [];
const g = 9.81;

for (const p of MOTION_PLATFORMS) {
  rows.push(
    run('pendulum', p.name, (i) => {
      const r = rng(1000 + i);
      const L = 0.4 + 1.1 * r.uniform();
      const truth = synthPendulum({ length: L, g, theta0: 0.1 + 0.3 * r.uniform(), sampleRate: 400, seed: 2000 + i });
      return { rec: captureOnPlatform(truth, p, 3000 + i), truth: g };
    }),
  );
  rows.push(
    run('centripetal', p.name, (i) => {
      const r = rng(4000 + i);
      const radius = 0.1 + 0.3 * r.uniform();
      const truth = synthCentripetal({
        radius,
        sampleRate: 400,
        seconds: 18,
        profile: i % 2 ? 'pushed' : 'decay',
        omega0: 5 + 4 * r.uniform(),
        seed: 5000 + i,
      });
      return { rec: captureOnPlatform(truth, p, 6000 + i), truth: radius * 100 };
    }),
  );
}

for (const rate of AUDIO_RATES) {
  rows.push(
    run('resonance', `Microphone at ${rate / 1000} kHz`, (i) => {
      const r = rng(7000 + i);
      const temperature = 15 + 13 * r.uniform();
      const truth = synthResonance({
        length: 0.15 + 0.25 * r.uniform(),
        diameter: 0.03 + 0.04 * r.uniform(),
        temperature,
        mode: i % 2 ? 1 : 0,
        sampleRate: rate,
        seed: 8000 + i,
      });
      return { rec: captureAudio(truth), truth: speedOfSound(temperature) };
    }),
  );
}

const pct = (x: number) => `${(x * 100).toFixed(2)} %`;
const table = [
  '| Experiment | Simulated platform | Success | Mean error | Worst error | Truth within ±2σ |',
  '|---|---|---|---|---|---|',
  ...rows.map((r) => {
    const mean = r.errors.length ? r.errors.reduce((a, b) => a + b, 0) / r.errors.length : NaN;
    const worst = r.errors.length ? Math.max(...r.errors) : NaN;
    const success = r.ok === 0 ? 'rejected with advice' : `${r.ok}/${RUNS}`;
    return `| ${r.experiment} | ${r.platform} | ${success} | ${r.ok ? pct(mean) : '—'} | ${r.ok ? pct(worst) : '—'} | ${r.ok ? `${Math.round((r.within2 / r.ok) * 100)} %` : '—'} |`;
  }),
].join('\n');

const STRESS_RUNS = 60;
const realistic = stress(STRESS_RUNS, false);
const realisticTable = [
  '| Correct experiment, realistic conditions | Agrees | Close | Far off | Too uncertain | Analysis failed |',
  '|---|---|---|---|---|---|',
  ...Object.entries(realistic).map(([name, c]) => `| ${name} | ${c.agrees} | ${c.close} | ${c.off} | ${c.imprecise} | ${c.failed} |`),
].join('\n');

const doc = `# Validation report

Generated by \`npm run validate\` (scripts/validate.ts). Deterministic: running it again gives the same numbers.

Each row runs ${RUNS} randomised setups (pendulum length 0.4–1.5 m and swing 6–23°;
chair radius 10–40 cm with free or hand-pushed spins; tubes 15–40 cm, open and closed,
15–28 °C) through a physics simulation, delivers the data the way that phone platform
would (see [COMPATIBILITY.md](COMPATIBILITY.md)), and compares PocketLab's result with
the simulated truth.

"Truth within ±2σ" checks that the reported uncertainty is honest: for an honest ±2σ
it should be close to 95 %. Much lower would mean PocketLab claims more precision than
it has; 100 % means the uncertainty is cautious.

${table}

## Does a careful student ever get a false error?

${STRESS_RUNS} correctly performed experiments per row, each with the imperfections that
happen anyway on a real phone (src/testing/realistic.ts): a trembling hand before release,
the phone hanging turned and twisting on the string, sensor bias, the phone being a 15 cm
object, tape-measure error; an uneven floor and seat vibration under the chair, the
accelerometer chip off the phone's centre; breath noise, mains hum, silence before blowing,
real rim shapes and an estimated room temperature for the tube. Delivered through simulated
iPhone and Android sensor streams. Counts are the verdict the student would see.

${realisticTable}

"Close" is not an error message: it tells the student the result is within 5 % but outside
the estimated uncertainty, and points to the sources of error. This check runs in the test
suite (src/experiments/realistic.test.ts) so a change that causes false alarms fails CI.

## What these numbers do not say

- They are **simulations**: real sensors add bias and noise that is not modelled, and
  students do not set up experiments perfectly. Real-device results are tracked
  separately in [COMPATIBILITY.md](COMPATIBILITY.md).
- They test the **analysis and platform handling**, not the physics model's own
  limits (e.g. the end correction of a real glass, the size of a real phone).
- A phone without a gyroscope cannot run the spinning-chair experiment; that row
  shows the app refusing with an explanation, which is the intended behaviour.
`;

writeFileSync(join(process.cwd(), 'docs', 'VALIDATION.md'), doc);
console.log(table);
