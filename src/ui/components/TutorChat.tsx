import { useEffect, useRef, useState } from 'react';
import { SUGGESTIONS } from '../tutor';

interface Message {
  role: 'user' | 'assistant';
  content: string;
}

/**
 * The AI tutor drawer. Answers come from /api/chat (server-side, so no API key
 * in the browser). The experiment's context is sent with each question.
 */
export function TutorChat({
  open,
  onClose,
  context,
  initialQuestion,
}: {
  open: boolean;
  onClose: () => void;
  context: () => string;
  initialQuestion?: string | null;
}) {
  const [messages, setMessages] = useState<Message[]>([]);
  const [draft, setDraft] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const list = useRef<HTMLDivElement>(null);
  const asked = useRef<string | null>(null);

  const send = async (text: string) => {
    const question = text.trim();
    if (!question || busy) return;
    const next = [...messages, { role: 'user' as const, content: question }].slice(-12);
    setMessages(next);
    setDraft('');
    setError(null);
    setBusy(true);
    try {
      const res = await fetch('/api/chat', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ messages: next, context: context() }),
      });
      const data = (await res.json().catch(() => ({}))) as { reply?: string; error?: string };
      if (res.ok && data.reply) setMessages([...next, { role: 'assistant', content: data.reply }]);
      else if (data.error === 'not_configured') setError('The AI tutor is not switched on for this website yet.');
      else setError(data.error ?? 'Something went wrong. Try again.');
    } catch {
      setError(navigator.onLine ? 'Could not reach the AI tutor. Try again.' : 'You are offline — the AI tutor needs internet. Everything else works offline.');
    } finally {
      setBusy(false);
    }
  };

  // A question from "Ask the AI tutor about this result" is sent as soon as the drawer opens.
  useEffect(() => {
    if (open && initialQuestion && asked.current !== initialQuestion) {
      asked.current = initialQuestion;
      void send(initialQuestion);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps -- send only once per question
  }, [open, initialQuestion]);

  useEffect(() => {
    list.current?.scrollTo({ top: list.current.scrollHeight, behavior: 'smooth' });
  }, [messages, busy]);

  if (!open) return null;
  return (
    <aside className="tutor no-print" role="dialog" aria-label="AI tutor">
      <header className="tutor-head">
        <strong>🤖 AI tutor</strong>
        <button className="icon" aria-label="Close the AI tutor" onClick={onClose}>
          ×
        </button>
      </header>
      <div className="tutor-list" ref={list} aria-live="polite">
        {messages.length === 0 && (
          <div className="tutor-intro">
            <p>Ask anything about this experiment or your result. I can see your numbers and how they were calculated.</p>
            <div className="chips">
              {SUGGESTIONS.map((s) => (
                <button key={s} className="chip" onClick={() => void send(s)}>
                  {s}
                </button>
              ))}
            </div>
          </div>
        )}
        {messages.map((m, i) => (
          <p key={i} className={`bubble ${m.role}`}>
            {m.content}
          </p>
        ))}
        {busy && <p className="bubble assistant typing">Thinking…</p>}
        {error && (
          <p className="tutor-error" role="alert">
            {error}
          </p>
        )}
      </div>
      <form
        className="tutor-form"
        onSubmit={(e) => {
          e.preventDefault();
          void send(draft);
        }}
      >
        <textarea
          rows={2}
          value={draft}
          maxLength={1000}
          placeholder="Type your question… (any language)"
          onChange={(e) => setDraft(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === 'Enter' && !e.shiftKey) {
              e.preventDefault();
              void send(draft);
            }
          }}
        />
        <button className="primary" type="submit" disabled={busy || !draft.trim()}>
          Send
        </button>
      </form>
      <p className="tutor-note">
        Answers are generated by AI (Groq) and can be wrong — check them against your own reasoning. Your question and this
        experiment’s numbers are sent to generate the answer; nothing else.
      </p>
    </aside>
  );
}
