/**
 * Core contracts of PocketLab. Everything else depends on these types;
 * these types depend on nothing. Keep them small and stable.
 */

/** Physical sensor families an experiment can ask for. */
export type SensorKind = 'motion' | 'audio';

/**
 * A captured measurement: uniformly sampled channels plus the parameters the
 * student entered. Recordings are plain JSON, so any analysis can be replayed
 * later, on any device, deterministically.
 */
export interface Recording {
  format: 'pocketlab.recording';
  version: 1;
  experimentId: string;
  sensor: SensorKind;
  /** Uniform sample rate of every channel, Hz. */
  sampleRate: number;
  /** ISO-8601 time the capture started. */
  startedAt: string;
  /**
   * Channel name → samples. Motion: ax, ay, az (m/s², incl. gravity) and
   * gx, gy, gz (rad/s). Audio: `audio` (normalised −1…1).
   */
  channels: Record<string, number[]>;
  params: Record<string, number>;
  meta?: {
    /** Generated by a physics simulation rather than a real sensor. */
    synthetic?: boolean;
    device?: string;
    note?: string;
  };
}

export type ParamSpec =
  | {
      kind: 'number';
      id: string;
      label: string;
      /** Unit shown to the student, e.g. "cm" — whatever a school ruler reads. */
      unit: string;
      /**
       * SI value = displayed value × scale (0.01 for cm). Recordings and
       * analyses always use SI; default/min/max/step are in displayed units.
       */
      scale?: number;
      default: number;
      min?: number;
      max?: number;
      step?: number;
      help?: string;
    }
  | {
      kind: 'choice';
      id: string;
      label: string;
      default: number;
      options: { value: number; label: string }[];
      help?: string;
    };

export interface Measurement {
  label: string;
  value: number;
  uncertainty?: number;
  unit: string;
  /** Significant decimals to show. */
  digits?: number;
}

/** Measured value vs an accepted reference — the headline of every result. */
export interface Comparison {
  quantity: string;
  symbol: string;
  measured: number;
  uncertainty: number;
  accepted: number;
  acceptedSource: string;
  unit: string;
  digits: number;
}

export interface Series {
  name: string;
  x: ArrayLike<number>;
  y: ArrayLike<number>;
  style: 'line' | 'points';
  /** Index into the chart palette. */
  color?: number;
}

export interface ChartSpec {
  title: string;
  xLabel: string;
  yLabel: string;
  series: Series[];
}

export type AnalysisResult =
  | {
      ok: true;
      primary: Comparison;
      measurements: Measurement[];
      charts: ChartSpec[];
      /** Human-readable derivation with the actual numbers plugged in. */
      steps: string[];
      warnings: string[];
      /** Machine-readable intermediate values (e.g. period T) for multi-trial summaries. */
      values?: Record<string, number>;
    }
  | { ok: false; error: string; hint?: string };

export type SuccessfulAnalysis = Extract<AnalysisResult, { ok: true }>;

/** One repetition of an experiment, as fed to multi-trial summaries. */
export interface TrialData {
  recording: Recording;
  result: SuccessfulAnalysis;
}

/**
 * The plugin contract. An experiment is pure data + one pure function:
 * adding a new experiment never requires touching the core or the UI.
 */
export interface ExperimentDefinition {
  id: string;
  title: string;
  tagline: string;
  subject: string;
  sensor: SensorKind;
  /** Capture length in seconds. */
  durationSec: number;
  /** Seconds between pressing Start and recording, to get into position. Default 3. */
  countdownSec?: number;
  params: ParamSpec[];
  materials: string[];
  instructions: string[];
  /**
   * Setup diagram as static SVG markup (kept framework-free so plugins never
   * depend on the UI). Use `currentColor` and the CSS variables --accent / --ink-2.
   */
  illustration?: string;
  /** Things that commonly go wrong, shown in the lab report's discussion. */
  errorSources?: string[];
  theory: {
    summary: string;
    /** Plain-text formula shown to the student, e.g. "g = 4π²L / T²". */
    formula: string;
  };
  /** Paths (under /public) of bundled sample recordings, loaded together as trials. */
  demoDatasets?: string[];
  /** Live-preview channel selector: one number per incoming sample. */
  preview: (sample: Record<string, number>) => number;
  previewLabel: string;
  analyze: (recording: Recording) => AnalysisResult;
  /**
   * Combines several trials (≥ 2) into one result — e.g. a T² vs L fit when
   * the pendulum length was varied. Return null to fall back to the default
   * mean ± standard error of the primary quantity.
   */
  summarize?: (trials: TrialData[]) => AnalysisResult | null;
}
